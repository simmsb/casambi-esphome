use crate::cloud::NetworkInfo;
use std::io::Write;

/// Sanitize a Casambi unit name for use as an ESPHome entity name.
/// ESPHome rejects `/` in names (URL path separator); also clean quotes/control chars.
pub fn sanitize_entity_name(name: &str) -> String {
    let mut out = String::with_capacity(name.len());
    let mut last_was_space = true; // trim leading whitespace
    for ch in name.chars() {
        let mapped = match ch {
            '/' | '\\' => Some(' '),
            '"' => Some('\''),
            c if c.is_control() => Some(' '),
            c => Some(c),
        };
        if let Some(c) = mapped {
            if c.is_whitespace() {
                if !last_was_space {
                    out.push(' ');
                    last_was_space = true;
                }
            } else {
                out.push(c);
                last_was_space = false;
            }
        }
    }
    let mut trimmed = out.trim().to_string();
    if trimmed.is_empty() {
        trimmed = "Light".to_string();
    }
    // ESPHome NAME_MAX_LENGTH is 120
    if trimmed.chars().count() > 120 {
        trimmed = trimmed.chars().take(120).collect();
        trimmed = trimmed.trim_end().to_string();
    }
    trimmed
}

pub fn emit_yaml(info: &NetworkInfo, out: &mut dyn Write) -> std::io::Result<()> {
    writeln!(out, "# Generated by casambi-config for network '{}'", info.network_name)?;
    writeln!(out, "# Cloud network id: {}", info.network_id)?;
    writeln!(
        out,
        "# Cloud protocolVersion: {} (informational only; device NodeInfo uses a different scheme)",
        info.protocol_version
    )?;
    writeln!(out, "# Key '{}' (id={}, role={})", info.key.name, info.key.id, info.key.role)?;
    writeln!(out)?;
    writeln!(out, "esp32_ble_tracker:")?;
    writeln!(out)?;
    writeln!(out, "ble_client:")?;
    writeln!(out, "  - mac_address: \"{}\"", info.mac_address)?;
    writeln!(out, "    id: casambi_ble")?;
    writeln!(out)?;
    writeln!(out, "casambi:")?;
    writeln!(out, "  ble_client_id: casambi_ble")?;
    writeln!(out, "  key_id: {}", info.key.id)?;
    writeln!(out, "  key: \"{}\"", info.key.key_hex)?;
    writeln!(out)?;
    writeln!(out, "binary_sensor:")?;
    writeln!(out, "  - platform: casambi")?;
    writeln!(out, "    name: \"Casambi Network\"")?;
    writeln!(out)?;
    writeln!(out, "light:")?;
    if info.units.is_empty() {
        writeln!(out, "  # (no units found in cloud config)")?;
    }
    for unit in &info.units {
        let safe_name = sanitize_entity_name(&unit.name);
        writeln!(out, "  - platform: casambi")?;
        writeln!(out, "    name: \"{safe_name}\"")?;
        writeln!(out, "    unit_id: {}", unit.device_id)?;
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn replaces_slashes() {
        assert_eq!(
            sanitize_entity_name("EXT/4ch/Dim,RGBW"),
            "EXT 4ch Dim,RGBW"
        );
    }

    #[test]
    fn replaces_quotes_and_collapses_space() {
        assert_eq!(sanitize_entity_name("  Hall  \"A\"  "), "Hall 'A'");
    }

    #[test]
    fn empty_becomes_light() {
        assert_eq!(sanitize_entity_name("///"), "Light");
    }
}
